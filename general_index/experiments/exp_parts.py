"""Global statistics from the live slice-0 sample files (read-only; files are still being appended).

Uses NPARTS of the 64 hash partitions (each is 1/64 of hash space, all docs seen so far).
  1. bucket (hash group) size distribution, and how the non-singleton share grows with corpus size
     (docs subsampled by id), to extrapolate to 107M docs
  2. candidate pairs produced at different group caps
  3. bytes/record after per-partition compaction (sort, truncate hash, delta + varint)
  4. per-doc sampled-5-gram count distribution (scaled from NPARTS/64)
"""
import os
import sys
import zlib

import numpy as np

D = "/home/arthur/Sites/dupefinder/general_index/data/slice0"
NPARTS = int(sys.argv[1]) if len(sys.argv) > 1 else 4
REC = np.dtype([("h", "<u8"), ("d", "<u4")])


def load(i):
    path = os.path.join(D, f"part_{i:02d}.bin")
    n = os.path.getsize(path) // REC.itemsize
    return np.fromfile(path, dtype=REC, count=n)


recs = np.concatenate([load(i) for i in range(NPARTS)])
recs = np.unique(recs)
ndocs = int(recs["d"].max()) + 1
print(f"{len(recs):,} records from {NPARTS}/64 partitions, {ndocs:,} docs seen so far")

# 4. per-doc counts
per_doc = np.bincount(recs["d"], minlength=ndocs) * (64 / NPARTS)
q = np.percentile(per_doc[per_doc > 0], [10, 50, 90, 99, 99.9])
print("sampled 5-grams per doc (mod-4, scaled to all partitions): p10/p50/p90/p99/p99.9 =",
      " / ".join(f"{x:.0f}" for x in q), f" mean {per_doc[per_doc > 0].mean():.0f}")
top = np.sort(per_doc)[::-1]
print(f"  storage share of the largest 1% of docs: {top[:ndocs // 100].sum() / top.sum():.1%}")


# 1. group sizes vs corpus fraction
def group_sizes(r):
    h = np.sort(r["h"])
    starts = np.concatenate(([0], np.flatnonzero(np.diff(h)) + 1))
    return np.diff(np.concatenate((starts, [len(h)])))


print("\ncorpus fraction -> docs, distinct hashes, share of RECORDS in groups >=2, in groups 2..20, >20")
for m in (16, 8, 4, 2, 1):
    r = recs[recs["d"] % m == 0]
    g = group_sizes(r)
    tot = g.sum()
    print(f"  1/{m:<3} {ndocs // m:>10,} docs  {len(g):>12,} hashes  "
          f">=2: {g[g >= 2].sum() / tot:6.2%}   2..20: {g[(g >= 2) & (g <= 20)].sum() / tot:6.2%}   "
          f">20: {g[g > 20].sum() / tot:6.2%}")

g = group_sizes(recs)
print("\ngroup-size histogram (all docs seen):")
for lo, hi in ((1, 1), (2, 2), (3, 5), (6, 20), (21, 100), (101, 1000), (1001, 10 ** 9)):
    sel = (g >= lo) & (g <= hi)
    print(f"  {lo:>5}-{hi if hi < 10**9 else 'inf':<5} groups {sel.sum():>12,}   records {g[sel].sum():>12,}")
print(f"  largest group: {g.max():,} docs")

# 2. pairs generated by cap
print("\npairs generated (sum of g*(g-1)/2) at caps, these partitions:")
for cap in (20, 100, 1000, 10000):
    sel = (g >= 2) & (g <= cap)
    print(f"  cap {cap:>6}: {int((g[sel] * (g[sel] - 1) // 2).sum()):>14,} pair-increments")

# 3. compaction
def varint_len(x):
    n = np.ones(len(x), np.int64)
    v = x.copy()
    for _ in range(9):
        v = v >> np.uint64(7)
        n += (v > 0)
    return int(n.sum())


print("\ncompaction (per partition, sorted, delta-coded):")
r = load(0)
r = np.unique(r)
for bits in (64, 48, 40):
    h = (r["h"] >> np.uint64(64 - bits)) if bits < 64 else r["h"]
    order = np.argsort(h, kind="stable")
    hs, ds = h[order], r["d"][order]
    delta = np.diff(np.concatenate(([np.uint64(0)], hs)))
    vl = varint_len(delta)
    raw = np.empty(len(hs), dtype=[("dh", "<u8"), ("d", "<u4")])
    raw["dh"], raw["d"] = delta, ds
    z = len(zlib.compress(delta.astype("<u8").tobytes(), 6)) + len(zlib.compress(ds.astype("<u4").tobytes(), 6))
    print(f"  {bits}-bit hash: varint deltas {vl / len(hs):.2f} B + 3 B doc id = {vl / len(hs) + 3:.2f} B/record;"
          f"  zlib(deltas)+zlib(ids) = {z / len(hs):.2f} B/record   (raw 12 B)")
